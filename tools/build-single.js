#!/usr/bin/env node
/* Builds Covenant-offline.html — the whole game in ONE file.
   Everything (CSS, JS, artwork, icons, fonts) is inlined as data URIs,
   so it runs from file:// with no server and no internet connection. */
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const R = (p) => path.join(ROOT, p);

const MIME = {
  ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png",
  ".svg": "image/svg+xml", ".woff2": "font/woff2", ".webmanifest": "application/manifest+json"
};

function collect(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) collect(p, out);
    else if (MIME[path.extname(e.name).toLowerCase()]) out.push(p);
  }
  return out;
}

const uri = new Map();
for (const abs of collect(R("assets"))) {
  const rel = path.relative(ROOT, abs).split(path.sep).join("/");
  const data = `data:${MIME[path.extname(abs).toLowerCase()]};base64,${fs.readFileSync(abs).toString("base64")}`;
  uri.set(rel, data);
  uri.set("../" + rel, data); // CSS uses ../assets/... because it lives in src/
}
const keys = [...uri.keys()].sort((a, b) => b.length - a.length);
const inline = (text) => {
  for (const k of keys) if (text.includes(k)) text = text.split(k).join(uri.get(k));
  return text;
};

const result = await build({
  entryPoints: [R("src/main.js")],
  bundle: true, format: "iife", target: "es2020", minify: true,
  write: false, legalComments: "none", logLevel: "silent"
});
const js = inline(result.outputFiles[0].text);
const css = inline(fs.readFileSync(R("src/styles.css"), "utf8"));
let html = fs.readFileSync(R("index.html"), "utf8");

html = inline(html);
html = html.replace(/<link rel="manifest"[^>]*>\s*/i, "");
html = html.replace(/<link rel="stylesheet" href="src\/styles\.css">/i, () => `<style>${css}</style>`);
html = html.replace(/<script type="module" src="src\/main\.js"><\/script>/i,
  () => `<script>${js.replace(/<\/script/gi, "<\\/script")}</script>`);
html = html.replace("<title>", "<!-- Covenant single-file offline build. Generated by tools/build-single.js -->\n  <title>");

const out = R("Covenant-offline.html");
fs.writeFileSync(out, html);
console.log(`Built Covenant-offline.html — ${(fs.statSync(out).size / 1024 / 1024).toFixed(2)} MB, fully self-contained.`);
